from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gen_tiling import generate, value, DEFAULT_OUT, MODES, MODES_3D

SCRIPT = Path(__file__).resolve().parent / "gen_tiling.py"


def make_synthetic_header():
    hdr = """
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE01[][8] = {
    { X0, X1, X2, X3, Y0, Y1, Y2, Y3 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE2[][4] = {
    { X0, X1, Y0, Y1 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE3[][4] = {
    { Z0, Z1, Z2, 0 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE4[][4] = {
    { S0, S1, S2, 0 },
};
"""
    for _, name in MODES + MODES_3D:
        hdr += f"""
const ADDR_SW_PATINFO {name}[] = {{
    {{ 0, 0, 0, 0, 0 }},
}};
"""
    return hdr


class GenTilingCliTests(unittest.TestCase):
    def test_help_flag_prints_usage_and_exits_zero(self):
        for flag in ("-h", "--help"):
            with self.subTest(flag=flag):
                res = subprocess.run(
                    [sys.executable, "-B", str(SCRIPT), flag],
                    capture_output=True,
                    text=True,
                )
                self.assertEqual(res.returncode, 0)
                self.assertIn("Generate crates/xcl/src/gpu/tiling_tables.rs from AMD addrlib", res.stdout)
                self.assertIn("scripts/gen_tiling.py", res.stdout)

    def test_missing_args_prints_usage_and_exits_code_2(self):
        res = subprocess.run(
            [sys.executable, "-B", str(SCRIPT)],
            capture_output=True,
            text=True,
        )
        self.assertEqual(res.returncode, 2)
        self.assertIn("scripts/gen_tiling.py", res.stdout)

    def test_nonexistent_file_exits_code_1_with_error(self):
        res = subprocess.run(
            [sys.executable, "-B", str(SCRIPT), "nonexistent_swizzle.h"],
            capture_output=True,
            text=True,
        )
        self.assertEqual(res.returncode, 1)
        self.assertIn("error: file not found", res.stderr)

    def test_missing_required_tables_exits_code_1_with_error(self):
        with tempfile.TemporaryDirectory() as tmp:
            bad_header = Path(tmp) / "empty.h"
            bad_header.write_text("// no tables here", encoding="utf-8")
            res = subprocess.run(
                [sys.executable, "-B", str(SCRIPT), str(bad_header)],
                capture_output=True,
                text=True,
            )
            self.assertEqual(res.returncode, 1)
            self.assertIn("error:", res.stderr)
            self.assertIn("not found in header", res.stderr)

    def test_default_out_path_points_to_tiling_tables(self):
        norm = Path(DEFAULT_OUT).resolve()
        self.assertEqual(norm.name, "tiling_tables.rs")
        self.assertEqual(norm.parent.name, "gpu")

    def test_cli_custom_output_path(self):
        with tempfile.TemporaryDirectory() as tmp:
            hdr_path = Path(tmp) / "gfx10SwizzlePattern.h"
            hdr_path.write_text(make_synthetic_header(), encoding="utf-8")
            out_file = Path(tmp) / "sub" / "tiling_tables.rs"

            res = subprocess.run(
                [sys.executable, "-B", str(SCRIPT), str(hdr_path), str(out_file)],
                capture_output=True,
                text=True,
            )
            self.assertEqual(res.returncode, 0)
            self.assertIn("wrote", res.stdout)
            self.assertTrue(out_file.is_file())
            content = out_file.read_text(encoding="utf-8")
            self.assertIn("// Generated by scripts/gen_tiling.py from AMD addrlib", content)
            self.assertIn("pub static NIBBLE01: [[u64; 8]; 1] = [", content)
            self.assertIn("pub static PATTERNS: &[(u32, &[[u16; 4]])] = &[", content)
            self.assertIn("pub static PATTERNS_3D: &[(u32, &[[u16; 4]])] = &[", content)


class GenTilingGenerateTests(unittest.TestCase):
    def test_value_parsing(self):
        self.assertEqual(value("0"), 0)
        self.assertEqual(value("0x10"), 16)
        self.assertEqual(value("X0"), 1 << 0)
        self.assertEqual(value("Y0"), 1 << 16)
        self.assertEqual(value("Z0"), 1 << 32)
        self.assertEqual(value("S0"), 1 << 48)
        self.assertEqual(value("X0 ^ 0x1"), 0)

    def test_value_rejects_unknown_token(self):
        with self.assertRaises(ValueError) as cm:
            value("UNKNOWN_TOKEN")
        self.assertIn("unknown swizzle token", str(cm.exception))

    def test_generate_synthetic_patterns(self):
        hdr = make_synthetic_header()
        content, stats = generate(hdr)
        used, pat, pat3 = stats
        self.assertEqual(len(used), 4)
        self.assertEqual(len(pat), len(MODES))
        self.assertEqual(len(pat3), len(MODES_3D))
        self.assertIn("#![allow(clippy::unreadable_literal)]", content)
        self.assertIn("pub static NIBBLE01: [[u64; 8]; 1] = [", content)
        self.assertIn("pub static PATTERNS: &[(u32, &[[u16; 4]])] = &[", content)
        self.assertIn("pub static PATTERNS_3D: &[(u32, &[[u16; 4]])] = &[", content)

    def test_generate_custom_modes(self):
        custom_hdr = """
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE01[][8] = {
    { X0, X1, X2, X3, Y0, Y1, Y2, Y3 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE2[][4] = {
    { X0, X1, Y0, Y1 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE3[][4] = {
    { Z0, Z1, Z2, 0 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE4[][4] = {
    { S0, S1, S2, 0 },
};
const ADDR_SW_PATINFO TEST_2D_PAT[] = {
    { 0, 0, 0, 0, 0 },
};
const ADDR_SW_PATINFO TEST_3D_PAT[] = {
    { 0, 0, 0, 0, 0 },
};
"""
        content, stats = generate(
            custom_hdr,
            modes=[(99, "TEST_2D_PAT")],
            modes_3d=[(88, "TEST_3D_PAT")],
        )
        self.assertIn("(99, &[[0, 0, 0, 0]]),", content)
        self.assertIn("(88, &[[0, 0, 0, 0]]),", content)

    def test_generate_rejects_malformed_row(self):
        bad_hdr = """
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE01[][8] = {
    { X0, X1, X2, X3, Y0, Y1, Y2, Y3 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE2[][4] = {
    { X0, X1, Y0, Y1 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE3[][4] = {
    { Z0, Z1, Z2, 0 },
};
const ADDR_BIT GFX10_SW_PATTERN_NIBBLE4[][4] = {
    { S0, S1, S2, 0 },
};
const ADDR_SW_PATINFO TEST_2D_PAT[] = {
    { 0, 0, 0 },
};
"""
        with self.assertRaises(ValueError) as cm:
            generate(bad_hdr, modes=[(1, "TEST_2D_PAT")], modes_3d=[])
        self.assertIn("expected 5 elements per row", str(cm.exception))


if __name__ == "__main__":
    unittest.main()
