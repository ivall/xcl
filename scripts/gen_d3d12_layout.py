"""Generate crates/xcl/src/hle/d3d12_layout.rs from d3d12.h (microsoft/DirectX-Headers, MIT).

Usage: python -I scripts/gen_d3d12_layout.py <d3d12.h> [out_rs]

Extracts, for every ID3D12* COM interface: IID, parent interface and the full vtable
method order (including inherited IUnknown/ID3D12Object methods) from the C-style
`XxxVtbl` structs. XCL uses PC order as the first guess for D3D12.X objects and names
every slot in its logs/reports.
"""

import os
import re
import sys

DEFAULT_OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "crates", "xcl", "src", "hle", "d3d12_layout.rs"
)


def generate(text):
    iids = {}
    parents = {}
    for m in re.finditer(r'MIDL_INTERFACE\("([0-9a-fA-F-]{36})"\)\s*(\w+)\s*:\s*public\s+(\w+)', text):
        iids[m.group(2)] = m.group(1).lower()
        parents[m.group(2)] = m.group(3)
    vtbls = {}
    for m in re.finditer(r"typedef struct (\w+)Vtbl\s*\{(.*?)\}\s*\1Vtbl;", text, re.S):
        name, body = m.group(1), m.group(2)
        raw = re.findall(r"\(\s*STDMETHODCALLTYPE\s*\*\s*(\w+)\s*\)", body)
        # struct-returning methods are declared twice (#if !defined(_WIN32) / #else)
        methods = [m for i, m in enumerate(raw) if i == 0 or raw[i - 1] != m]
        vtbls[name] = methods
    names = sorted(n for n in vtbls if n.startswith("ID3D12") and n in iids)
    if not names:
        raise ValueError("no ID3D12 interfaces found")

    out = [
        "// @generated by scripts/gen_d3d12_layout.py from d3d12.h (microsoft/DirectX-Headers, MIT) – do not edit.",
        "",
        "pub struct Iface {",
        "    pub name: &'static str,",
        "    pub iid: &'static str,",
        "    pub parent: &'static str,",
        "    pub methods: &'static [&'static str],",
        "}",
        "",
        "pub static IFACES: &[Iface] = &[",
    ]
    for n in names:
        ms = ", ".join(f'"{x}"' for x in vtbls[n])
        out.append(f'    Iface {{ name: "{n}", iid: "{iids[n]}", parent: "{parents.get(n, "")}", methods: &[{ms}] }},')
    out.append("];\n")

    devices = [n for n in names if re.fullmatch(r"ID3D12Device\d*", n)]
    dev = max(devices, key=lambda n: len(vtbls[n])) if devices else None
    dev_count = len(vtbls[dev]) if dev else 0
    return "\n".join(out), names, dev, dev_count


def main(argv=None):
    args = argv if argv is not None else sys.argv[1:]
    if not args or args[0] in ("-h", "--help"):
        print(__doc__.strip())
        return 0 if (args and args[0] in ("-h", "--help")) else 2

    src = args[0]
    if not os.path.isfile(src):
        print(f"error: file not found: '{src}'", file=sys.stderr)
        return 1

    dst = args[1] if len(args) > 1 else DEFAULT_OUT
    text = open(src, encoding="utf-8", errors="replace").read()
    try:
        content, names, dev, dev_count = generate(text)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    out_dir = os.path.dirname(os.path.abspath(dst))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    open(dst, "w", encoding="utf-8", newline="\n").write(content)
    dev_msg = f"most derived device {dev} with {dev_count} methods" if dev else "no device interface"
    print(f"{len(names)} interfaces; {dev_msg} -> {os.path.normpath(dst)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
