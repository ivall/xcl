"""Turn VIctory's bcpack-tables.bin into Rust constants for XCL.

bcpack-tables.bin is from the VIctory repo (github.com/Marvisak/VIctory),
victory-formats/bcpack-tables.bin.

Layout is that of the format's constant tables: 128 x 9 u16 model frequencies, the
rank tables, 512 u16 BC7 control words, then 255 dictionary entries per format.
BC7 entry 0 stores all 32 signed indices directly after its two index widths; entries
1..254 repeat the two width bytes first and store 16 + 15 signed indices (VIctory PR #658).

    python -I scripts/gen_bcpack_victory_tables.py <bcpack-tables.bin> [out.rs]
"""
import os
import struct
import sys

MODELS, BUCKETS, DICTIONARY = 128, 9, 255
TABLES_BIN_SIZE = 77982

DEFAULT_OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "crates", "xcl", "src", "hle", "bcpack", "tables.rs"
)


class R:
    def __init__(self, b):
        self.b, self.i = b, 0

    def take(self, n):
        if self.i + n > len(self.b):
            raise ValueError(f"unexpected end of data at offset {self.i}, needed {n} bytes")
        v = self.b[self.i:self.i + n]
        self.i += n
        return v

    def u8(self):
        return self.take(1)[0]

    def u16(self):
        return struct.unpack("<H", self.take(2))[0]

    def i16(self):
        return struct.unpack("<h", self.take(2))[0]


def rows(vals, per, fmt):
    out = []
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(fmt(v).rstrip(",") for v in vals[i:i + per]) + ",")
    return "\n".join(out)


def rows2(vals, per):
    out = []
    for i in range(0, len(vals), per):
        out.append("    [%s]," % ", ".join("%du32" % v for v in vals[i:i + per]))
    return "\n".join(out)


def generate(blob):
    if len(blob) != TABLES_BIN_SIZE:
        raise ValueError(f"expected {TABLES_BIN_SIZE} bytes in bcpack-tables.bin, got {len(blob)}")
    r = R(blob)
    freq = [r.u16() for _ in range(MODELS * BUCKETS)]
    rank1 = list(r.take(256))
    rank3a = list(r.take(64))
    rank3c = list(r.take(256))
    rank4 = list(r.take(64))
    rank5 = list(r.take(64))
    ctrl7 = [r.u16() for _ in range(512)]

    def plain(ep, ix):
        out = []
        for _ in range(DICTIONARY):
            out.append((list(r.take(ep)), [r.u8() for _ in range(ix)]))
        return out

    bc1, bc3, bc4, bc5 = plain(6, 16), plain(8, 32), plain(2, 16), plain(4, 32)
    bc6 = []
    for _ in range(DICTIONARY):
        r.u8()
        e = [r.u16() for _ in range(12)]
        mode = r.u8()
        ix = [r.i16() for _ in range(16)]
        bc6.append((e, mode, ix))
    bc7 = []
    for entry in range(DICTIONARY):
        ctrl = r.u16()
        ep = [r.u16() for _ in range(24)]
        bits = [r.u8(), r.u8()]
        if entry == 0:
            ix = [r.i16() for _ in range(32)]
        else:
            r.u16()  # the widths again; not indices
            ix = [r.i16() for _ in range(31)] + [0]  # set 1 has 15 slots, unused
        bc7.append((ctrl, ep, bits, ix))
    if r.i != len(r.b):
        raise ValueError(f"consumed {r.i} bytes, expected {len(r.b)}")

    def plain_entries(items):
        out = []
        for ep, ix in items:
            e = ep + [0] * (8 - len(ep))
            i = ix + [0] * (32 - len(ix))
            out.append("    Plain { ep: [%s], ix: [%s] }," % (
                ", ".join(map(str, e)), ", ".join(map(str, i))))
        return "\n".join(out)

    src_lines = [
        "// Generated by scripts/gen_bcpack_victory_tables.py from VIctory's",
        "// bcpack-tables.bin; the format's constant tables, not derived here.",
        "",
        "pub const MODELS: usize = %d;" % MODELS,
        "pub const BUCKETS: usize = %d;" % BUCKETS,
        "pub const DICTIONARY: usize = %d;" % DICTIONARY,
        "",
        "#[derive(Clone, Copy, Default)]",
        "pub struct Plain { pub ep: [u8; 8], pub ix: [u8; 32] }",
        "#[derive(Clone, Copy, Default)]",
        "pub struct Bc6Ep { pub e: [[u16; 3]; 4] }",
        "#[derive(Clone, Copy, Default)]",
        "pub struct Bc6Ix { pub mode: u8, pub ix: [i16; 16] }",
        "#[derive(Clone, Copy, Default)]",
        "pub struct Bc7Ep { pub ctrl: u16, pub rows: [[u16; 8]; 3] }",
        "#[derive(Clone, Copy, Default)]",
        "pub struct Bc7Ix { pub bits: [u8; 2], pub ix: [[i16; 16]; 2] }",
        "",
        "pub static FREQ: [[u32; BUCKETS]; MODELS] = [",
        rows2(freq, BUCKETS),
        "];",
        "pub static RANK1: [u8; 256] = [%s];" % ", ".join(map(str, rank1)),
        "pub static RANK3A: [u8; 64] = [%s];" % ", ".join(map(str, rank3a)),
        "pub static RANK3C: [u8; 256] = [%s];" % ", ".join(map(str, rank3c)),
        "pub static RANK4: [u8; 64] = [%s];" % ", ".join(map(str, rank4)),
        "pub static RANK5: [u8; 64] = [%s];" % ", ".join(map(str, rank5)),
        "pub static CTRL7: [u16; 512] = [%s];" % ", ".join(map(str, ctrl7)),
        "pub static BC1: [Plain; DICTIONARY] = [",
        plain_entries(bc1), "];",
        "pub static BC3: [Plain; DICTIONARY] = [",
        plain_entries(bc3), "];",
        "pub static BC4: [Plain; DICTIONARY] = [",
        plain_entries(bc4), "];",
        "pub static BC5: [Plain; DICTIONARY] = [",
        plain_entries(bc5), "];",
        "pub static BC6: [(Bc6Ep, Bc6Ix); DICTIONARY] = [",
    ]
    for e, mode, ix in bc6:
        src_lines.append(
            "    (Bc6Ep { e: [[%s], [%s], [%s], [%s]] }, Bc6Ix { mode: %d, ix: [%s] })," % (
                ", ".join(map(str, e[0:3])), ", ".join(map(str, e[3:6])),
                ", ".join(map(str, e[6:9])), ", ".join(map(str, e[9:12])),
                mode, ", ".join(map(str, ix))))
    src_lines += ["];", "pub static BC7: [(Bc7Ep, Bc7Ix); DICTIONARY] = ["]
    for ctrl, ep, bits, ix in bc7:
        rows_3 = ", ".join("[%s]" % ", ".join(map(str, ep[k:k + 8])) for k in range(0, 24, 8))
        src_lines.append(
            "    (Bc7Ep { ctrl: %d, rows: [%s] }, Bc7Ix { bits: [%d, %d], ix: [[%s], [%s]] })," % (
                ctrl, rows_3, bits[0], bits[1],
                ", ".join(map(str, ix[:16])), ", ".join(map(str, ix[16:]))))
    src_lines += ["];", ""]
    return "\n".join(src_lines), (len(bc1), len(bc3), len(bc4), len(bc5), len(bc6), len(bc7))


def main(argv=None):
    args = argv if argv is not None else sys.argv[1:]
    if not args or args[0] in ("-h", "--help"):
        print(__doc__.strip())
        return 0 if (args and args[0] in ("-h", "--help")) else 2

    src = args[0]
    if not os.path.isfile(src):
        print(f"error: file not found: '{src}'", file=sys.stderr)
        return 1

    dst = args[1] if len(args) > 1 else DEFAULT_OUT
    blob = open(src, "rb").read()
    try:
        content, counts = generate(blob)
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    out_dir = os.path.dirname(os.path.abspath(dst))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    open(dst, "w", encoding="utf-8", newline="\n").write(content)
    print("wrote", os.path.normpath(dst), "entries", *counts)
    return 0


if __name__ == "__main__":
    sys.exit(main())
