"""Generate crates/xcl/src/hle/xgameruntime/gdk_table.rs from a table of the GDK runtime's
functions: every function with the class, interface and vtable slot its thunk uses
(QueryApiImpl protocol), as extracted from the public PC GDK's xgameruntime.lib. Input lines:
`NAME(function, "class guid", "interface guid", slot)`.

usage: python scripts/gen_gdk_table.py <table file> [out_rs]"""
import io, os, re, sys

DEFAULT_OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), '..', 'crates', 'xcl', 'src', 'hle', 'xgameruntime', 'gdk_table.rs'
)


def hexg(g):
    return '0x' + g.replace('-', '').lower()


def generate(src):
    origin = re.search(r'Source\s*:\s*(\S+)', src)
    rows = re.findall(r'\w+\((\w+), "([0-9A-Fa-f-]{36})", "([0-9A-Fa-f-]{36})", (\d+)\)', src)
    if not rows:
        raise ValueError('no rows')

    lines = [
        '//! Generated by scripts/gen_gdk_table.py – do not edit.',
        f'//! The GDK runtime\'s functions as the public PC GDK\'s xgameruntime.lib ({origin.group(1) if origin else "?"}) calls them:',
        '//! the (class, interface) its thunk asks QueryApiImpl for and the vtable slot it calls.',
        '',
        '/// (function, class id, interface id, slot)',
        'pub static API: &[(&str, u128, u128, u8)] = &[',
    ]
    for name, c, i, slot in sorted(rows, key=lambda r: (r[1], r[2], int(r[3]))):
        lines.append(f'    ("{name}", {hexg(c)}, {hexg(i)}, {slot}),')
    lines.append('];\n')
    return '\n'.join(lines), rows


def main(argv=None):
    args = argv if argv is not None else sys.argv[1:]
    if not args or args[0] in ('-h', '--help'):
        print(__doc__.strip())
        return 0 if (args and args[0] in ('-h', '--help')) else 2

    table_path = args[0]
    if not os.path.isfile(table_path):
        print(f"error: file not found: '{table_path}'", file=sys.stderr)
        return 1

    out_path = args[1] if len(args) > 1 else DEFAULT_OUT
    src = io.open(table_path, encoding='utf-8').read()
    try:
        content, rows = generate(src)
    except ValueError:
        print(f"error: no GDK API rows found in '{table_path}'", file=sys.stderr)
        return 1

    out_dir = os.path.dirname(os.path.abspath(out_path))
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    with io.open(out_path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(content)

    print(len(rows), 'rows ->', os.path.normpath(out_path))
    return 0


if __name__ == '__main__':
    sys.exit(main())
